package dev.whitedev.jpi.protocol;

public enum Operation {
    PING, METRICS, CLASSES, CLASS_BYTES, EXECUTE, FIELDS, THREAD_DUMP,
    DISCONNECT, CLASS_EVENTS, ENVIRONMENT, CONSTANT_SEARCH,
    REDEFINE_SOURCE, ROLLBACK_CLASS, CLASS_METHODS, PATCH_METHOD,
    APPLY_CLASS_BYTES, TRACE_START, TRACE_STOP, TRACE_EVENTS,
    METHOD_XREFS, XREF_SEARCH, DEOBFUSCATION_INVENTORY,
    API_HOOK_START, API_HOOK_STOP, API_HOOK_EVENTS,
    HEAP_SCAN, HEAP_OBJECT, HEAP_DUMP,
    CFG_ANALYZE, CFG_TRACE_START, CFG_TRACE_STOP, CFG_SNAPSHOT,
    FIELD_WRITE_SITES, FIELD_TRACE_START, FIELD_TRACE_STOP, FIELD_TRACE_EVENTS,
    TRACE_GRAPH, TRACE_GRAPH_CLEAR;

    public static Operation fromCode(int code) {
        return values()[code];
    }
}
